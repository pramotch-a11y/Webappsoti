-- SAfordata Room Booking - Supabase/PostgreSQL schema
-- Review this file before running it in Supabase SQL Editor.

create extension if not exists pgcrypto;

create table if not exists public.affiliation (
  affiliation_id bigint generated by default as identity primary key,
  affiliation_name varchar(255) not null
);

create table if not exists public.users (
  user_id bigint generated by default as identity primary key,
  auth_user_id uuid unique references auth.users(id) on delete set null,
  full_name varchar(255) not null,
  email varchar(100) not null,
  phone varchar(20),
  role_level varchar(50) not null default 'STUDENT' check (role_level in ('STUDENT','TEACHER','STAFF','ADMIN')),
  account_status varchar(50) not null default 'ACTIVE' check (account_status in ('ACTIVE','SUSPENDED','INACTIVE')),
  affiliation_affiliation_id bigint references public.affiliation(affiliation_id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  is_deleted smallint not null default 0 check (is_deleted in (0,1)),
  deleted_at timestamptz
);
create unique index if not exists uq_users_email_active on public.users (lower(email)) where is_deleted = 0;

create table if not exists public.staff (
  staff_id bigint generated by default as identity primary key,
  job_title varchar(100),
  start_date date,
  staff_status varchar(50) default 'ACTIVE',
  users_user_id bigint unique references public.users(user_id)
);

create table if not exists public.building (
  building_id bigint generated by default as identity primary key,
  building_name varchar(255) not null,
  address varchar(255)
);

create table if not exists public.floor (
  floor_id bigint generated by default as identity primary key,
  floor_number varchar(50) not null,
  building_building_id bigint not null references public.building(building_id)
);

create table if not exists public.room_type (
  room_type_id bigint generated by default as identity primary key,
  type_name varchar(100) not null,
  description varchar(500)
);

create table if not exists public.room (
  room_id bigint generated by default as identity primary key,
  room_name varchar(100) not null,
  capacity integer check (capacity is null or capacity >= 0),
  room_status varchar(50) not null default 'AVAILABLE' check (room_status in ('AVAILABLE','MAINTENANCE','CLOSED')),
  image_url varchar(500),
  floor_floor_id bigint references public.floor(floor_id),
  room_type_room_type_id bigint references public.room_type(room_type_id),
  is_deleted smallint not null default 0 check (is_deleted in (0,1)),
  deleted_at timestamptz
);

create table if not exists public.equipment (
  equipment_id bigint generated by default as identity primary key,
  equipment_name varchar(255) not null,
  equipment_type varchar(100),
  equipment_status varchar(50) not null default 'AVAILABLE' check (equipment_status in ('AVAILABLE','IN_USE','MAINTENANCE','BROKEN')),
  total_qty integer not null default 0 check (total_qty >= 0),
  remaining_qty integer not null default 0 check (remaining_qty >= 0 and remaining_qty <= total_qty),
  usage_type varchar(20) not null default 'BORROWABLE' check (usage_type in ('FIXED','BORROWABLE','BOTH')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by_user_id bigint references public.users(user_id),
  is_deleted smallint not null default 0 check (is_deleted in (0,1)),
  deleted_at timestamptz
);

create table if not exists public.room_equipment (
  room_room_id bigint not null references public.room(room_id),
  equipment_equipment_id bigint not null references public.equipment(equipment_id),
  quantity integer check (quantity is null or quantity > 0),
  equip_status varchar(50) default 'AVAILABLE',
  primary key (room_room_id, equipment_equipment_id)
);

create table if not exists public.booking (
  booking_id bigint generated by default as identity primary key,
  booking_date date not null,
  start_time timestamp not null,
  end_time timestamp not null,
  purpose varchar(500),
  booking_status varchar(50) not null default 'PENDING' check (booking_status in ('PENDING','APPROVED','REJECTED','CANCELLED','CHECKED_IN','COMPLETED','NO_SHOW')),
  actual_checkin_time timestamp,
  users_user_id bigint not null references public.users(user_id),
  room_room_id bigint not null references public.room(room_id),
  staff_staff_id bigint references public.staff(staff_id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  approved_at timestamptz,
  reject_reason varchar(500),
  constraint ck_booking_time check (end_time > start_time),
  constraint ck_booking_date_match check (booking_date = start_time::date)
);

create table if not exists public.booking_participant (
  booking_booking_id bigint not null references public.booking(booking_id) on delete cascade,
  users_user_id bigint not null references public.users(user_id),
  participation_status varchar(50) default 'INVITED' check (participation_status in ('INVITED','ACCEPTED','DECLINED','ATTENDED')),
  primary key (booking_booking_id, users_user_id)
);

create table if not exists public.booking_equipment (
  booking_booking_id bigint not null references public.booking(booking_id) on delete cascade,
  equipment_equipment_id bigint not null references public.equipment(equipment_id),
  borrowed_qty integer not null check (borrowed_qty > 0),
  primary key (booking_booking_id, equipment_equipment_id)
);

create table if not exists public.penalty (
  penalty_id bigint generated by default as identity primary key,
  penalty_type varchar(100),
  start_date date,
  end_date date,
  reason varchar(500),
  penalty_status varchar(50) default 'ACTIVE' check (penalty_status in ('ACTIVE','EXPIRED','REVOKED')),
  users_user_id bigint not null references public.users(user_id),
  staff_staff_id bigint references public.staff(staff_id),
  booking_booking_id bigint references public.booking(booking_id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ck_penalty_date check (end_date is null or start_date is null or end_date >= start_date)
);

create table if not exists public.holiday (
  holiday_id bigint generated by default as identity primary key,
  holiday_date date not null unique,
  description varchar(255)
);

create table if not exists public.room_assignment (
  staff_staff_id bigint not null references public.staff(staff_id),
  room_room_id bigint not null references public.room(room_id),
  start_date date,
  work_shift varchar(50),
  primary key (staff_staff_id, room_room_id)
);

create table if not exists public.booking_log (
  booking_log_id bigint generated by default as identity primary key,
  action_type varchar(100) not null,
  action_time timestamptz not null default now(),
  violation_flag smallint not null default 0 check (violation_flag in (0,1)),
  booking_booking_id bigint not null references public.booking(booking_id),
  users_user_id bigint not null references public.users(user_id)
);

create table if not exists public.notification (
  notification_id bigint generated by default as identity primary key,
  noti_type varchar(50) check (noti_type in ('BOOKING_CREATED','BOOKING_APPROVED','BOOKING_REJECTED','BOOKING_CANCELLED','REMINDER','PENALTY')),
  content varchar(1000),
  recipient_email varchar(100),
  send_time timestamp,
  template_code varchar(50) not null,
  params_json jsonb,
  booking_booking_id bigint references public.booking(booking_id),
  users_user_id bigint not null references public.users(user_id),
  created_at timestamptz not null default now()
);

create table if not exists public.report (
  report_id bigint generated by default as identity primary key,
  report_type varchar(100) not null check (report_type in ('DAILY','WEEKLY','MONTHLY','YEARLY')),
  report_date date not null,
  total_bookings integer not null default 0,
  total_hours numeric(8,2) not null default 0,
  canceled_count integer default 0,
  users_user_id bigint references public.users(user_id),
  created_at timestamptz not null default now()
);

create index if not exists idx_booking_availability on public.booking(room_room_id, start_time, end_time);
create index if not exists idx_booking_user_history on public.booking(users_user_id, created_at);
create index if not exists idx_booking_staff on public.booking(staff_staff_id);
create index if not exists idx_be_equipment on public.booking_equipment(equipment_equipment_id);
create index if not exists idx_bpart_user on public.booking_participant(users_user_id);
create index if not exists idx_blog_booking on public.booking_log(booking_booking_id);
create index if not exists idx_blog_user on public.booking_log(users_user_id);
create index if not exists idx_noti_booking on public.notification(booking_booking_id);
create index if not exists idx_noti_user on public.notification(users_user_id);
create index if not exists idx_penalty_user on public.penalty(users_user_id);
create index if not exists idx_penalty_booking on public.penalty(booking_booking_id);
create index if not exists idx_report_user on public.report(users_user_id);
create index if not exists idx_rassign_room on public.room_assignment(room_room_id);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_users_updated_at on public.users;
create trigger trg_users_updated_at before update on public.users for each row execute function public.set_updated_at();
drop trigger if exists trg_equipment_updated_at on public.equipment;
create trigger trg_equipment_updated_at before update on public.equipment for each row execute function public.set_updated_at();
drop trigger if exists trg_booking_updated_at on public.booking;
create trigger trg_booking_updated_at before update on public.booking for each row execute function public.set_updated_at();
drop trigger if exists trg_penalty_updated_at on public.penalty;
create trigger trg_penalty_updated_at before update on public.penalty for each row execute function public.set_updated_at();

